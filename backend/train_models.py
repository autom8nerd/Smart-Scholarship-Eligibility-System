def main():
    """
    Main orchestration entrypoint for training pipeline.
    """
    print("\n" + "=" * 80)
    print("SMART SCHOLARSHIP MACHINE LEARNING TRAINING PIPELINE")
    print("=" * 80)
    
    chemins_possibles = [
        os.environ.get("CHEMIN_DATASET"),
        os.path.join(os.path.dirname(__file__), '..', 'moroccan_students_scholarship_dataset.csv'),
        os.path.join(os.path.dirname(__file__), 'moroccan_students_scholarship_dataset.csv'),
        os.path.join(os.path.dirname(__file__), 'donnees', 'moroccan_students_scholarship_dataset.csv'),
    ]
    chemin_csv = None
    for c in chemins_possibles:
        if c and os.path.exists(c):
            chemin_csv = os.path.abspath(c)
            break

    if not chemin_csv:
        print(f"[✗] Dataset not found in prospective paths.")
        print("[*] Please run first: python generate_dataset.py")
        return

    donnees = charger_donnees_reelles(chemin_csv, test_size=0.2)

    if not donnees:
        print("[✗] Failed to load dataset. Aborting.")
        return

    # Train all 3 models
    results = entrainer_modeles(donnees)

    # Display evaluation summary
    afficher_rapport(results, donnees)


if __name__ == "__main__":
    main()
