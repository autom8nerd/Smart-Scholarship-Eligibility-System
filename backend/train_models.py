def charger_donnees_reelles(chemin_csv, test_size=0.2):
    """
    Loads synthetic dataset and partitions into 80/20 train/test splits.

    Each model trains strictly on the feature subset that its corresponding
    /api/v1/predictions endpoint expects at inference time.
    """
    print(f"\n[*] Loading dataset...")
    try:
        df = pd.read_csv(chemin_csv)
        print(f"[✓] Dataset loaded: {len(df):,} rows, {len(df.columns)} columns")
    except Exception as e:
        print(f"[✗] Error loading dataset: {e}")
        return None

    # Print summary statistics
    print(f"\nDataset Statistics:")
    print(f"  GPA: [{df['gpa'].min():.2f}, {df['gpa'].max():.2f}]")
    print(f"  Exam Score: [{df['exam_score'].min():.2f}, {df['exam_score'].max():.2f}]")
    print(f"  Family Income: [{df['family_income'].min():.0f}, {df['family_income'].max():.0f}] MAD")
    print(f"  Dependents: [{df['dependents'].min():.0f}, {df['dependents'].max():.0f}]")
    print(f"  Distance: [{df['distance_km'].min():.2f}, {df['distance_km'].max():.2f}] km")

    # Prepare feature matrices aligned with endpoint inference expectations
    X_regression = df[['gpa', 'exam_score', 'family_income', 'dependents']].values
    X_arbre = df[['gpa', 'family_income', 'dependents']].values
    X_svm = df[['gpa', 'exam_score', 'family_income', 'distance_km']].values

    y_regression = df['financial_capacity_score'].values
    y_arbre = df['scholarship_class'].values
    y_svm = df['enrollment_probability_class'].values

    # Train/Test 80/20 partition
    X_train_reg, X_test_reg, y_train_reg, y_test_reg = train_test_split(
        X_regression, y_regression, test_size=test_size, random_state=42
    )

    X_train_arb, X_test_arb, y_train_arb, y_test_arb = train_test_split(
        X_arbre, y_arbre, test_size=test_size, random_state=42
    )

    X_train_svm, X_test_svm, y_train_svm, y_test_svm = train_test_split(
        X_svm, y_svm, test_size=test_size, random_state=42
    )

    print(f"\n[✓] Data split completed:")
    print(f"    Train: {len(X_train_reg):,} (80%)")
    print(f"    Test:  {len(X_test_reg):,} (20%)")

    return {
        'regression': (X_train_reg, X_test_reg, y_train_reg, y_test_reg),
        'arbre': (X_train_arb, X_test_arb, y_train_arb, y_test_arb),
        'svm': (X_train_svm, X_test_svm, y_train_svm, y_test_svm),
        'dataframe': df,
    }


def entrainer_modeles(donnees):
    """
    Trains the 3 ML models on the dataset partitions.
    """
    print("\n" + "=" * 80)
    print("TRAINING MACHINE LEARNING MODELS")
    print("=" * 80)
    
    X_train_reg, X_test_reg, y_train_reg, y_test_reg = donnees['regression']
    X_train_arb, X_test_arb, y_train_arb, y_test_arb = donnees['arbre']
    X_train_svm, X_test_svm, y_train_svm, y_test_svm = donnees['svm']
    
    results = {}
    
    # 1. LINEAR REGRESSION
    print("\n[1/3] Linear Regression — Financial Capacity Scoring")
    print("-" * 80)
    try:
        print(f"[*] Training model on {len(X_train_reg):,} samples...")
        modele_regression.entraîner(X_train_reg, y_train_reg)
        
        print(f"[*] Evaluating model on {len(X_test_reg):,} test samples...")
        y_pred_reg = modele_regression.modele.predict(X_test_reg)
        
        mse = mean_squared_error(y_test_reg, y_pred_reg)
        rmse = np.sqrt(mse)
        r2 = r2_score(y_test_reg, y_pred_reg)
        mae = np.mean(np.abs(y_test_reg - y_pred_reg))
        
        results['regression'] = {
            'mse': float(mse),
            'rmse': float(rmse),
            'mae': float(mae),
            'r2': float(r2)
        }
        
        print(f"[✓] SUCCESS")
        print(f"    R² Score: {r2:.4f} ({r2*100:.2f}% explained variance)")
        print(f"    RMSE:     {rmse:.4f}")
        print(f"    MAE:      {mae:.4f}")
        
    except Exception as e:
        print(f"[✗] ERROR: {e}")
    
    # 2. DECISION TREE CLASSIFIER
    print("\n[2/3] Decision Tree — Scholarship Tier Allocation")
    print("-" * 80)
    try:
        print(f"[*] Training model on {len(X_train_arb):,} samples...")
        modele_arbre.entraîner(X_train_arb, y_train_arb)
        
        print(f"[*] Evaluating model on {len(X_test_arb):,} test samples...")
        y_pred_arb = modele_arbre.modele.predict(X_test_arb)
        
        accuracy = accuracy_score(y_test_arb, y_pred_arb)
        precision = precision_score(y_test_arb, y_pred_arb, average='weighted', zero_division=0)
        recall = recall_score(y_test_arb, y_pred_arb, average='weighted', zero_division=0)
        f1 = f1_score(y_test_arb, y_pred_arb, average='weighted', zero_division=0)
        
        results['arbre'] = {
            'accuracy': float(accuracy),
            'precision': float(precision),
            'recall': float(recall),
            'f1': float(f1)
        }
        
        print(f"[✓] SUCCESS")
        print(f"    Accuracy:  {accuracy*100:.2f}%")
        print(f"    Precision: {precision:.4f}")
        print(f"    Recall:    {recall:.4f}")
        print(f"    F1-Score:  {f1:.4f}")
        
    except Exception as e:
        print(f"[✗] ERROR: {e}")
    
    # 3. SVM (using SGDClassifier with StandardScaler)
    print("\n[3/3] SGD Classifier (SVM) — Enrollment Probability")
    print("-" * 80)
    try:
        print(f"[*] Training model on {len(X_train_svm):,} samples...")
        print(f"    (SGDClassifier with StandardScaler for efficient margin convergence)")
        modele_svm.entraîner(X_train_svm, y_train_svm)
        
        print(f"[*] Evaluating model on {len(X_test_svm):,} test samples...")
        y_pred_svm = modele_svm.modele.predict(modele_svm.scaler.transform(X_test_svm))
        
        accuracy = accuracy_score(y_test_svm, y_pred_svm)
        precision = precision_score(y_test_svm, y_pred_svm, average='weighted', zero_division=0)
        recall = recall_score(y_test_svm, y_pred_svm, average='weighted', zero_division=0)
        f1 = f1_score(y_test_svm, y_pred_svm, average='weighted', zero_division=0)
        
        results['svm'] = {
            'accuracy': float(accuracy),
            'precision': float(precision),
            'recall': float(recall),
            'f1': float(f1)
        }
        
        print(f"[✓] SUCCESS")
        print(f"    Accuracy:  {accuracy*100:.2f}%")
        print(f"    Precision: {precision:.4f}")
        print(f"    Recall:    {recall:.4f}")
        print(f"    F1-Score:  {f1:.4f}")
        
    except Exception as e:
        print(f"[✗] ERROR: {str(e)[:100]}...")
        print(f"[!] Continuing despite SVM error")
    
    return results


